# Security-urgency keywords: a lost/stolen card is a fraud risk even
# though "card_issue" is medium-priority by default.
URGENT_KEYWORDS = ["ضاعت", "انسرقت", "مسروق", "سرقة"]


def apply_priority_overrides(category, text, base_priority):
    if category == "card_issue" and any(k in text for k in URGENT_KEYWORDS):
        return "high"
    return base_priority


